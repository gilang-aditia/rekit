import * as React from "react"
import { ContextMenu as ContextMenuPrimitive } from "radix-ui"
import { CheckIcon, ChevronRightIcon, CircleIcon } from "lucide-react"

import { cn } from "@/lib/utils"

/** Root/Sub/Group Radix tidak merender elemen DOM, jadi tidak ada ref untuk diteruskan. */
function ContextMenu(
  props: React.ComponentPropsWithoutRef<typeof ContextMenuPrimitive.Root>
) {
  return <ContextMenuPrimitive.Root data-slot="context-menu" {...props} />
}

function ContextMenuSub(
  props: React.ComponentPropsWithoutRef<typeof ContextMenuPrimitive.Sub>
) {
  return <ContextMenuPrimitive.Sub data-slot="context-menu-sub" {...props} />
}

function ContextMenuPortal(
  props: React.ComponentPropsWithoutRef<typeof ContextMenuPrimitive.Portal>
) {
  return <ContextMenuPrimitive.Portal data-slot="context-menu-portal" {...props} />
}

const ContextMenuTrigger = React.forwardRef<
  React.ElementRef<typeof ContextMenuPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof ContextMenuPrimitive.Trigger>
>(({ ...props }, ref) => (
  <ContextMenuPrimitive.Trigger
    ref={ref}
    data-slot="context-menu-trigger"
    {...props}
  />
))
ContextMenuTrigger.displayName = "ContextMenuTrigger"

